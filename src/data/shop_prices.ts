export interface ShopOffer {
  /** Ključ shopa (npr. "univerzalno") */
  shop_key: string;
  /** Naziv prodavnice: Univerzalno, IQ Mobile, fonTELe, Mobitech, Digital City */
  shop: string;
  /** Naziv proizvoda tačno kako ga shop prikazuje */
  naziv: string;
  /** Cijena u KM iz shopa (stvarna, ne demo) */
  cijena_km: number;
  /** Dostupnost sa stranice proizvoda ("Na stanju"/"Rasprodato"…) ili null */
  dostupnost: string | null;
  /** Link na stranicu proizvoda u shopu */
  url: string;
  /** Datum preuzimanja (ISO) */
  datum: string;
}

export interface PhoneShopPrices {
  /** Slug telefona iz kataloga (src/data/phones.ts) */
  slug: string;
  /** Naziv modela kakav je u katalogu, npr. "iPhone 15" */
  modelLabel: string;
  /** Najniža cijena DOSTUPNE ponude u shopovima (KM); null = sve rasprodato */
  minPrice: number | null;
  /** Broj prikazanih ponuda (najviše 8) */
  count: number;
  /** Broj prikazanih ponuda koje nisu rasprodato */
  availableCount: number;
  /** Najniža zabilježena cijena bez obzira na dostupnost (KM) */
  minListedPrice: number;
  /** Ponude sortirane rastuće po cijeni (najviše 8) */
  offers: ShopOffer[];
  /** Prodavnice koje imaju ovaj model (abecedno) */
  sources: string[];
}

